BEGIN;

CREATE TABLE IF NOT EXISTS memberships (
    mid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mname VARCHAR(50) NOT NULL UNIQUE,
    score INTEGER NOT NULL DEFAULT 0,

    CONSTRAINT chk_membership_name
        CHECK (char_length(trim(mname)) > 0),

    CONSTRAINT chk_membership_score
        CHECK (score >= 0)
);

CREATE TABLE IF NOT EXISTS customers (
    uid INTEGER PRIMARY KEY,
    fullname VARCHAR(100) NOT NULL DEFAULT '',
    mid INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_customer_uid
        CHECK (uid > 0),

    CONSTRAINT fk_customer_membership
        FOREIGN KEY (mid)
        REFERENCES memberships(mid)
);

INSERT INTO memberships (mname, score)
VALUES ('STANDARD', 0)
ON CONFLICT (mname) DO NOTHING;

COMMIT;
