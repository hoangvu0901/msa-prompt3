BEGIN;

CREATE TABLE IF NOT EXISTS orders (
    oid INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uid INTEGER NOT NULL,
    request_id UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    membership_score INTEGER NOT NULL DEFAULT 0,
    discount_rate NUMERIC(5,2) NOT NULL DEFAULT 0,
    subtotal NUMERIC(18,2) NOT NULL DEFAULT 0,
    discount NUMERIC(18,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(18,2) NOT NULL DEFAULT 0,

    failure_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_orders_customer_request
        UNIQUE (uid, request_id),

    CONSTRAINT chk_orders_uid
        CHECK (uid > 0),

    CONSTRAINT chk_orders_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$'),

    CONSTRAINT chk_orders_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'FAILED')),

    CONSTRAINT chk_orders_membership_score
        CHECK (membership_score >= 0),

    CONSTRAINT chk_orders_discount_rate
        CHECK (discount_rate >= 0 AND discount_rate <= 100),

    CONSTRAINT chk_orders_amounts
        CHECK (
            subtotal >= 0
            AND discount >= 0
            AND discount <= subtotal
            AND total_amount = subtotal - discount
        )
);

CREATE TABLE IF NOT EXISTS order_details (
    oid INTEGER NOT NULL,
    pid INTEGER NOT NULL,
    qty INTEGER NOT NULL,
    unit_price NUMERIC(10,2) NOT NULL,

    CONSTRAINT pk_order_details
        PRIMARY KEY (oid, pid),

    CONSTRAINT fk_order_details_order
        FOREIGN KEY (oid)
        REFERENCES orders(oid),

    CONSTRAINT chk_order_details_pid
        CHECK (pid > 0),

    CONSTRAINT chk_order_details_qty
        CHECK (qty > 0),

    CONSTRAINT chk_order_details_price
        CHECK (unit_price >= 0)
);

CREATE TABLE IF NOT EXISTS outbox_events (
    event_id UUID PRIMARY KEY,
    event_type VARCHAR(100) NOT NULL,
    aggregate_id INTEGER NOT NULL,
    payload JSONB NOT NULL,

    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ,

    CONSTRAINT fk_outbox_order
        FOREIGN KEY (aggregate_id)
        REFERENCES orders(oid),

    CONSTRAINT chk_outbox_attempts
        CHECK (attempts >= 0),

    CONSTRAINT chk_outbox_payload
        CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX IF NOT EXISTS idx_orders_uid_oid
    ON orders (uid, oid DESC);

CREATE INDEX IF NOT EXISTS idx_orders_pending
    ON orders (created_at)
    WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS idx_outbox_pending
    ON outbox_events (next_attempt_at, created_at)
    WHERE published_at IS NULL;

COMMIT;
